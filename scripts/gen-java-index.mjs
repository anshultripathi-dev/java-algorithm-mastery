// Collects every java/**/*.java file into a generated TS module so that the website
// (Vite) and the PDF generator (Node) read exactly the same, verified source files.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const javaDir = path.join(root, 'java');
const out = path.join(root, 'src', 'data', 'generated', 'java-sources.ts');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(p)));
    else if (e.name.endsWith('.java') || e.name.endsWith('.in') || e.name.endsWith('.out')) files.push(p);
  }
  return files;
}

const files = (await walk(javaDir)).sort();
const map = {};
const io = {};
for (const f of files) {
  const rel = path.relative(javaDir, f).split(path.sep).join('/');
  const text = await readFile(f, 'utf8');
  if (rel.endsWith('.java')) map[rel] = text.replace(/\s+$/, '') + '\n';
  else {
    const key = rel.replace(/\.(in|out)$/, '.java');
    (io[key] ??= {})[rel.endsWith('.in') ? 'in' : 'out'] = text;
  }
}
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, `// AUTO-GENERATED by scripts/gen-java-index.mjs — do not edit.\nexport const JAVA_SOURCES: Record<string, string> = ${JSON.stringify(map, null, 1)};\nexport const JAVA_IO: Record<string, { in?: string; out?: string }> = ${JSON.stringify(io, null, 1)};\n`);
console.log(`java index: ${Object.keys(map).length} programs, ${Object.keys(io).length} with sample I/O → src/data/generated/java-sources.ts`);
